//! # void-trust
//!
//! Сеть доверия: подписанные поручительства между узлами и расчёт доверия
//! **от лица своего узла** (см. `Obsidian/Сеть доверия.md`).
//!
//! Без центрального органа нельзя доказать, что ключ — один живой человек.
//! Зато можно ответить, насколько узел доверен МНЕ: доверие течёт от меня по
//! цепочкам поручительств, ослабевает с каждым шагом и делится между теми, за
//! кого поручитель поручился. Ботов можно создать сколько угодно, но к честной
//! части сети они цепляются через немногих обманутых людей — и весят в сумме не
//! больше их доли.
//!
//!   - [`types`] — поручительство [`Vouch`] и его подпись;
//!   - [`engine`] — расчёт уровней и весов [`compute`] (чистая функция);
//!   - [`store`] — хранение поручительств и наблюдений в SQLite.

pub mod engine;
pub mod error;
pub mod store;
pub mod types;

pub use engine::{compute, TrustInfo, TrustInputs, TrustLevel, TrustMap};
pub use error::TrustError;
pub use types::{Vouch, VouchKind};
